import SwiftUI

/// Справка — одна страница, которая помещается на экране целиком.
///
/// Читать её будут один раз и в спешке, поэтому здесь только то, чего не видно из самого
/// окна: что означают значки, почему часть моделей не проверяется и куда смотреть, если
/// пусто. Всё остальное — в README.
struct HelpView: View {
    var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: 14) {
                Group {
                    head("Что показывает значок")
                    line("**19/21** — отвечают 19 из 21 моделей, которые мы проверяем. "
                         + "**⚠** — часть не в порядке. **✗** — молчит сам шлюз. "
                         + "**«не настроен»** — не указан адрес.")
                }
                Group {
                    head("Значки у моделей")
                    line("**✅** ответила · **⚠️** ответила и отказала · **✗** не ответила · "
                         + "**•** не проверяется")
                    line("Отказ — это не обрыв связи: сервер жив, а сломана настройка модели "
                         + "на кластере. Ожиданием такое не проходит.")
                }
                Group {
                    head("Как часто спрашиваем")
                    line("Список моделей — раз в минуту, это обычный запрос и он ничего не "
                         + "стоит. Настоящий запрос к каждой модели — раз в 15 минут: он "
                         + "занимает общий кластер.")
                    line("Картинки, речь и OCR настоящим запросом **не проверяются** — это "
                         + "стоило бы целой генерации. Они показаны как «в списке».")
                }
                Group {
                    head("Скрыть лишнее")
                    line("В меню навести на модель → «Скрыть эту модель». Где именно её "
                         + "прятать — две галочки в «Настройках…», там же кнопка «Вернуть». "
                         + "Скрытые опрашиваются как обычно: прячется только показ.")
                }
                Group {
                    head("История")
                    line("Полоса по каждой модели: **зелёное** — отвечала, **красное** — "
                         + "молчала, **оранжевое** — отвечала и отказала, **серое** — не "
                         + "спрашивали. Смотреть стоит не на среднее, а на тех, кто внизу.")
                }
                Group {
                    head("Если что-то не так")
                    line("Журнал: `~/Library/Application Support/GPUStackMonitor/monitor.log` "
                         + "— первое место, куда смотреть, если значок молчит.")
                }
            }
            .padding(20)
        }
        .frame(width: 460, height: 520)
    }

    private func head(_ s: String) -> some View {
        Text(s).font(.system(size: 12, weight: .semibold))
    }

    private func line(_ s: String) -> some View {
        Text(.init(s)).font(.system(size: 12)).fixedSize(horizontal: false, vertical: true)
    }
}
